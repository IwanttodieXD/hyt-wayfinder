-- ============================================================================
--
-- SITUATION
-- ---------
-- Migration 20260101000012 seeded the 131-person orientation cohort but stopped
-- partway: the users exist, the courses do not, and every course_id is NULL.
--
-- The cause is in 0012 itself. Its INSERT names five columns that NO migration
-- ever created:
--
--   last_name, first_name, middle_name, middle_initial, name_extension
--
-- 0011 and 0010 add course_id; 0012 adds orientation_status. Nothing adds the
-- name parts. So that INSERT raised 42703 (column does not exist) and aborted.
-- Whatever created the user rows did so by another route.
--
-- This migration is therefore the fix for a partial load, not a routine step.
-- It is written to be safe whether or not those columns exist, and whether or
-- not the earlier parts of 0012 ran.
--
-- WHAT IT DOES
-- ------------
--   1. Creates the five missing name columns, IF they are genuinely absent.
--      IF NOT EXISTS throughout, so it is a no-op on a database that already
--      has them.
--   2. Inserts the five programme rows into public.courses.
--   3. Backfills users.course_id by matching users.name against the roster.
--   4. Makes users.email nullable and retires the placeholder addresses.
--
-- WHY MATCHING IS DONE ON users.name
-- ----------------------------------
-- The name-part columns cannot be trusted: they were never populated (that is
-- the whole problem), and re-deriving them from a free-text name is guesswork.
-- users.name is NOT NULL from 0001 and already holds the value 0012 computed,
-- so matching on it is both exact and safe.
--
-- IF SECTION 3 REPORTS 0 ROWS UPDATED
-- -------------------------------------
-- The stored names do not match the roster, which means the rows came from
-- somewhere other than 0012. Do NOT force the match by editing names to suit.
-- Section 4 below is a diagnostic that lists what is actually stored; read it
-- and adjust from there.
--
-- Safe to re-run: every step is idempotent.
-- ============================================================================


-- ----------------------------------------------------------------------------
