-- 1. Every cohort row now has a course. Expect 131.
SELECT count(*) AS cohort_rows,
       count(*) FILTER (WHERE course_id IS NULL) AS still_no_course
FROM public.users u
JOIN public.courses c ON c.id = u.course_id
WHERE c.label IN (
  'Barista NC II', 'Event Management Services NC II', 'Housekeeping NC II',
  'Hilot (Wellness) Services NC II', 'Massage NC II');

-- 2. Counts per programme. Expect 58 / 10 / 52 / 10 / 1 = 131.
--    The Massage NC II sheet was truncated in the source, so 1 is a floor.
SELECT c.label AS programme, count(*) AS people,
       count(*) FILTER (WHERE u.email IS NULL) AS no_email
FROM public.users u
JOIN public.courses c ON c.id = u.course_id
WHERE c.label IN (
  'Barista NC II', 'Event Management Services NC II', 'Housekeeping NC II',
  'Hilot (Wellness) Services NC II', 'Massage NC II')
GROUP BY 1 ORDER BY 1;

-- 3. THE 24 WHO CANNOT SIGN IN. This is the list to work from when collecting
--    addresses. They may well be approved, but with no address there is no way
--    to prove who they are, so /verify sends them to the front desk.
SELECT c.label AS programme, u.name, u.last_name, u.first_name
FROM public.users u
LEFT JOIN public.courses c ON c.id = u.course_id
WHERE u.email IS NULL AND u.archived_at IS NULL
ORDER BY 1, u.last_name, u.first_name;

-- 4. DIAGNOSTIC - ONLY IF SECTION 3 UPDATED 0 ROWS.
--    Shows the names actually stored, so the roster VALUES list can be corrected
--    to match. Do NOT edit stored names to fit the roster; find out why they
--    differ first.
SELECT u.name, u.email, c.label AS programme
FROM public.users u
LEFT JOIN public.courses c ON c.id = u.course_id
WHERE u.name ILIKE ANY (ARRAY['%aranda%', '%casiano%', '%pamintuan%'])
ORDER BY u.name;

-- 5. auth.users and public.users disagreeing. Section 4 writes both, but Auth
--    may hold rows this migration never saw.
SELECT u.name, u.email AS profile_email, a.email AS auth_email
FROM public.users u
JOIN auth.users a ON a.id = u.id
WHERE u.email IS DISTINCT FROM a.email;

-- 6. Name + course collisions. These are the only duplicates that affect
--    /verify, which matches on both and refuses when more than one row returns.
SELECT c.label, u.name, count(*)
FROM public.users u
JOIN public.courses c ON c.id = u.course_id
WHERE u.archived_at IS NULL
GROUP BY 1, 2 HAVING count(*) > 1;


