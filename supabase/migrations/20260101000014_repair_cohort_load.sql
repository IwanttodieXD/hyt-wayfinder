-- ----------------------------------------------------------------------------
-- 4. Nullable email, and retire the placeholder addresses
-- ----------------------------------------------------------------------------
-- The 24 people with no address on the roster were given a synthetic
-- '*.pending@orientation.hyt.local' by 0012 so the NOT NULL constraint could be
-- satisfied. Those are not addresses: they cannot receive anything, so a visitor
-- who reached one was told to "check your email" for a link that could never
-- arrive. NULL states the same fact honestly and lets the UI route them to the
-- front desk instead.
ALTER TABLE public.users ALTER COLUMN email DROP NOT NULL;

COMMENT ON COLUMN public.users.email IS
  'Nullable. NULL means no usable address is on file, so this person cannot sign '
  'in until the registrar supplies one. verify_visitor returns has_email=false '
  'for these and /verify sends them to the front desk rather than promising a '
  'link that cannot be delivered.';

-- auth.users first. public.users.id references auth.users(id), NOT the address,
-- so nulling this cannot orphan a profile row - but the placeholder is equally
-- meaningless on the Auth side, and GoTrue is what ultimately validates it.
UPDATE auth.users
SET email = NULL
WHERE email LIKE '%.pending@orientation.hyt.local';

-- Then the profile copy.
UPDATE public.users
SET email = NULL
WHERE email LIKE '%.pending@orientation.hyt.local';

-- The UNIQUE constraint is deliberately KEPT. It is what stops two people
-- sharing an address, and in Postgres a UNIQUE column permits any number of
-- NULLs - so dropping NOT NULL above does not weaken it. Dropping the
-- constraint instead would allow duplicates, which is the property that matters.

-- A surviving placeholder would be a bug in the seed, not a person, so fail
-- loudly rather than leave a fake address in the table.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.users WHERE email LIKE '%orientation.hyt.local') THEN
    RAISE EXCEPTION 'placeholder addresses remain in public.users';
  END IF;
END
$$;


